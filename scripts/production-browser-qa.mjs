import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
import {chromium} from 'playwright-core';
const base=process.env.QA_BASE_URL??'http://127.0.0.1:3100';
const login=await fetch(base+'/api/session',{method:'POST',headers:{'content-type':'application/json',origin:base,'sec-fetch-site':'same-origin'},body:JSON.stringify({email:'operator@example.test',password:(await readFile('deploy/secrets/initial-admin-password','utf8')).trim()})});
assert.equal(login.status,200);
const pair=login.headers.get('set-cookie').split(';')[0],split=pair.indexOf('=');
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--disable-background-networking']});
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'dark'});
 await context.addCookies([{name:pair.slice(0,split),value:pair.slice(split+1),url:base,httpOnly:true,sameSite:'Lax'}]);
 const page=await context.newPage(),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(base+'/?view=agents',{waitUntil:'domcontentloaded'});
 const demo=page.getByRole('button',{name:'Live Demo',exact:true});
 await demo.waitFor({timeout:60000});
 const originalColor=await demo.evaluate(e=>getComputedStyle(e).backgroundColor);
 await page.getByRole('button',{name:'Campaign',exact:true}).click();
 let dialog=page.getByRole('dialog').last();
 await dialog.getByRole('button',{name:'3. Message & replies',exact:true}).click();
 const html=dialog.getByRole('textbox',{name:'Reply HTML template',exact:true});
 await html.fill('<table><tr><td>Campaign browser check {{message}}</td></tr></table>');
 const save=dialog.getByRole('button',{name:'Save',exact:true}).last();
 assert.equal(await save.evaluate(e=>getComputedStyle(e).backgroundColor),originalColor,'Save must match the existing Live Demo blue.');
 await save.click();
 await dialog.getByText(/saved/i).first().waitFor();
 await dialog.getByRole('button',{name:'Close',exact:true}).last().click();
 await page.getByRole('button',{name:'Campaign',exact:true}).click();
 dialog=page.getByRole('dialog').last();
 await dialog.getByRole('button',{name:'3. Message & replies',exact:true}).click();
 assert.match(await dialog.getByRole('textbox',{name:'Reply HTML template',exact:true}).inputValue(),/Campaign browser check/);
 await dialog.getByRole('button',{name:'Expand preview',exact:true}).click();
 const preview=page.getByRole('dialog').last();
 await preview.getByRole('textbox',{name:'HTML template',exact:true}).fill('<p>Live edit {{message}}</p>');
 await page.frameLocator('iframe[title="Expanded campaign email preview"]').getByText(/Live edit/).waitFor();
 await preview.getByRole('button',{name:'Close',exact:true}).first().click();
 await page.getByRole('dialog').last().getByRole('button',{name:'Close',exact:true}).last().click();
 await demo.click();
 dialog=page.getByRole('dialog').first();
 const demoSave=dialog.getByRole('button',{name:'Save',exact:true});
 await demoSave.waitFor();
 assert.equal(await demoSave.evaluate(e=>getComputedStyle(e).backgroundColor),originalColor);
 const demoTemplate=dialog.getByRole('textbox',{name:'Reply HTML template',exact:true});
 await demoTemplate.fill('<p>Demo browser check {{message}}</p>');
 await demoSave.click();
 await dialog.getByText('Demo reply template saved.',{exact:true}).waitFor();
 await page.keyboard.press('Escape');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.getByRole('button',{name:'Live Demo',exact:true}).click();
 await page.getByRole('textbox',{name:'Reply HTML template',exact:true}).waitFor();
 assert.match(await page.getByRole('textbox',{name:'Reply HTML template',exact:true}).inputValue(),/Demo browser check/);
 await mkdir('/tmp/ctx-production-qa',{recursive:true});
 await page.screenshot({path:'/tmp/ctx-production-qa/demo-desktop.png'});
 await page.keyboard.press('Escape');
 await page.keyboard.press('Meta+b');
 await page.getByRole('button',{name:'Campaign',exact:true}).click();
 await page.getByRole('dialog').last().getByRole('button',{name:'3. Message & replies',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/ctx-production-qa/campaign-mobile.png'});
 assert.ok(await page.getByRole('textbox',{name:'Reply HTML template',exact:true}).isVisible());
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'Page must not overflow horizontally.');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({campaignNavigation:true,campaignSave:true,demoSaveReload:true,livePreview:true,saveMatchesLiveDemo:originalColor,collapsedNavigation:true,mobile:true,pageErrors:errors}));
}finally{await browser.close();}
